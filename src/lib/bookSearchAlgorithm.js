/**
 * Sorts array of books instantly in memory
 */
export function applySortToResults(books, sortBy) {
  if (!Array.isArray(books)) return [];
  const list = [...books];

  switch (sortBy) {
    case 'year_desc':
      return list.sort((a, b) => {
        const yA = parseInt(a.publishedDate?.slice(0, 4) || '0', 10);
        const yB = parseInt(b.publishedDate?.slice(0, 4) || '0', 10);
        return yB - yA;
      });

    case 'year_asc':
      return list.sort((a, b) => {
        const yA = parseInt(a.publishedDate?.slice(0, 4) || '9999', 10);
        const yB = parseInt(b.publishedDate?.slice(0, 4) || '9999', 10);
        return yA - yB;
      });

    case 'title_asc':
      return list.sort((a, b) => (a.title || '').localeCompare(b.title || ''));

    case 'pages_desc':
      return list.sort((a, b) => (b.total_pages || 0) - (a.total_pages || 0));

    case 'pages_asc':
      return list.sort((a, b) => (a.total_pages || 0) - (b.total_pages || 0));

    default: // relevance
      return list;
  }
}

// Smart Genre Extraction & Normalization Helper
export function cleanGenre(rawSubjects, defaultGenre = 'General') {
  if (!rawSubjects) return defaultGenre;
  const list = Array.isArray(rawSubjects) ? rawSubjects : [rawSubjects];

  const ignorePatterns = [
    /new york times/i,
    /protected daisy/i,
    /accessible book/i,
    /in library/i,
    /open syllabus/i,
    /internet archive/i,
    /fictitious character/i,
    /imaginary place/i,
    /lending library/i,
    /large type/i,
    /overdrive/i,
    /reading level/i,
    /audiobook/i,
    /uncategorized/i,
  ];

  const PRIORITY_GENRES = [
    'Science Fiction',
    'Sci-Fi',
    'Cyberpunk',
    'Fantasy',
    'Dystopian',
    'Gothic Fiction',
    'Horror',
    'Philosophy',
    'Classic Literature',
    'Mystery',
    'Thriller',
    'Psychology',
    'Technology',
    'Computer Science',
    'History',
    'Biography',
    'Poetry',
    'Drama',
    'Adventure',
    'Romance',
    'Self-Improvement',
  ];

  // 1. Check priority matches first
  for (const s of list) {
    if (typeof s !== 'string') continue;
    for (const g of PRIORITY_GENRES) {
      if (s.toLowerCase().includes(g.toLowerCase())) {
        return g;
      }
    }
  }

  // 2. Otherwise pick the cleanest subject
  for (const s of list) {
    if (typeof s !== 'string') continue;
    let clean = s.replace(/^category:\s*/i, '').replace(/\s*--\s*fiction$/i, '').trim();
    if (clean.includes('/')) {
      const parts = clean.split('/').map((p) => p.trim());
      clean = parts[parts.length - 1] || parts[0];
    }
    if (clean.includes(',')) {
      const parts = clean.split(',').map((p) => p.trim());
      clean = parts[parts.length - 1] || parts[0];
    }
    if (clean.length >= 3 && clean.length <= 25 && !ignorePatterns.some((p) => p.test(clean))) {
      return clean.charAt(0).toUpperCase() + clean.slice(1);
    }
  }

  return defaultGenre;
}

// 1. Instant Curated & Local Fuzzy Matcher with field filtering
export function getLocalCuratedSuggestions(query, filterBy = 'all') {
  if (!query || !query.trim()) {
    return CURATED_SUGGESTIONS.slice(0, 6);
  }

  const normQuery = normalize(query);
  const words = normQuery.split(/\s+/).filter(Boolean);

  return CURATED_SUGGESTIONS.filter((book) => {
    const normTitle = normalize(book.title);
    const normAuthor = normalize(book.author);
    const normDesc = normalize(book.description);
    const normGenre = normalize(book.genre || book.category);

    if (filterBy === 'title') {
      return normTitle.includes(normQuery) || words.every((w) => normTitle.includes(w));
    }
    if (filterBy === 'author') {
      return normAuthor.includes(normQuery) || words.every((w) => normAuthor.includes(w));
    }
    if (filterBy === 'subject') {
      return normGenre.includes(normQuery) || normDesc.includes(normQuery);
    }

    if (normTitle.includes(normQuery) || normAuthor.includes(normQuery) || normGenre.includes(normQuery)) return true;
    return words.every(
      (w) => normTitle.includes(w) || normAuthor.includes(w) || normDesc.includes(w) || normGenre.includes(w)
    );
  });
}

// 2. Fetch from Project Gutenberg (Gutendex) - 70k+ Literary Works
async function fetchGutendex(query, filterBy, signal) {
  try {
    let url = `https://gutendex.com/books/?search=${encodeURIComponent(query)}`;
    if (filterBy === 'subject') {
      url = `https://gutendex.com/books/?topic=${encodeURIComponent(query)}`;
    }

    const res = await fetch(url, { signal });
    if (!res.ok) return [];

    const data = await res.json();
    if (!data.results || data.results.length === 0) return [];

    return data.results.slice(0, 8).map((b) => {
      const cleanTitle = (b.title || 'Untitled').replace(/\r?\n|\r/g, ' ');
      const authors = (b.authors || []).map((a) => {
        if (!a.name) return 'Unknown';
        const parts = a.name.split(', ');
        return parts.length === 2 ? `${parts[1]} ${parts[0]}` : a.name;
      });

      const cover =
        b.formats?.['image/jpeg'] ||
        `https://placehold.co/300x450/1e293b/ffffff?text=${encodeURIComponent(cleanTitle.slice(0, 10))}`;

      const year = b.authors?.[0]?.death_year ? String(b.authors[0].death_year - 20) : 'Classic';
      const genre = cleanGenre([...(b.bookshelves || []), ...(b.subjects || [])], 'Classic Literature');

      return {
        id: `gd-${b.id}`,
        title: cleanTitle,
        author: authors.join(', ') || 'Unknown Author',
        genre: genre,
        category: genre,
        total_pages: Math.max(120, (b.download_count % 350) + 180),
        thumbnail_url: cover,
        description: b.subjects?.slice(0, 3).join(', ') || 'Public Domain Classic via Project Gutenberg',
        publishedDate: year,
        source: 'Project Gutenberg',
      };
    });
  } catch (err) {
    if (err.name === 'AbortError') throw err;
    return [];
  }
}

// 3. Fetch from Google Books API with query qualification
async function fetchGoogleBooks(query, filterBy, signal) {
  if (isGoogleBooksThrottled) return null;

  try {
    let qualifiedQuery = query;
    if (filterBy === 'title') qualifiedQuery = `intitle:${query}`;
    else if (filterBy === 'author') qualifiedQuery = `inauthor:${query}`;
    else if (filterBy === 'subject') qualifiedQuery = `subject:${query}`;

    const endpoint = `https://www.googleapis.com/books/v1/volumes?q=${encodeURIComponent(
      qualifiedQuery
    )}&maxResults=8`;

    const res = await fetch(endpoint, { signal });

    if (!res.ok) {
      if (res.status === 429) {
        isGoogleBooksThrottled = true;
      }
      return null;
    }

    const data = await res.json();
    if (!data.items || data.items.length === 0) return [];

    return data.items.map((item) => {
      const info = item.volumeInfo || {};
      const thumb =
        info.imageLinks?.thumbnail?.replace('http://', 'https://') ||
        info.imageLinks?.smallThumbnail?.replace('http://', 'https://') ||
        `https://placehold.co/300x450/1e293b/ffffff?text=${encodeURIComponent(info.title || 'Book')}`;

      const genre = cleanGenre(info.categories, 'General');

      return {
        id: `gb-${item.id}`,
        title: info.title || 'Untitled',
        author: info.authors ? info.authors.join(', ') : 'Unknown Author',
        genre: genre,
        category: genre,
        total_pages: Number(info.pageCount) > 0 ? Number(info.pageCount) : 250,
        thumbnail_url: thumb,
        description: info.description || '',
        publishedDate: info.publishedDate || '',
        source: 'Google Books',
      };
    });
  } catch (err) {
    if (err.name === 'AbortError') throw err;
    return null;
  }
}

// 4. Fast Open Library API with trimmed payload fields and subject genre
async function fetchOpenLibrary(query, filterBy, signal) {
  try {
    let param = `q=${encodeURIComponent(query)}`;
    if (filterBy === 'title') param = `title=${encodeURIComponent(query)}`;
    else if (filterBy === 'author') param = `author=${encodeURIComponent(query)}`;
    else if (filterBy === 'subject') param = `subject=${encodeURIComponent(query)}`;

    const endpoint = `https://openlibrary.org/search.json?${param}&fields=key,title,author_name,cover_i,number_of_pages_median,first_publish_year,subtitle,subject&limit=8`;

    const res = await fetch(endpoint, { signal });
    if (!res.ok) return [];

    const data = await res.json();
    if (!data.docs || data.docs.length === 0) return [];

    return data.docs.map((doc, idx) => {
      const coverUrl = doc.cover_i
        ? `https://covers.openlibrary.org/b/id/${doc.cover_i}-M.jpg`
        : `https://placehold.co/300x450/1e293b/ffffff?text=${encodeURIComponent((doc.title || 'Book').slice(0, 10))}`;

      const pages =
        doc.number_of_pages_median ||
        doc.number_of_pages ||
        (Array.isArray(doc.edition_key) ? 280 : 250);

      const author = Array.isArray(doc.author_name)
        ? doc.author_name.slice(0, 2).join(', ')
        : 'Unknown Author';

      const genre = cleanGenre(doc.subject, 'Fiction');

      return {
        id: `ol-${doc.key?.replace('/works/', '') || idx}-${doc.cover_i || idx}`,
        title: doc.title || 'Untitled',
        author: author,
        genre: genre,
        category: genre,
        total_pages: Number(pages) > 0 ? Number(pages) : 250,
        thumbnail_url: coverUrl,
        description: doc.subtitle || '',
        publishedDate: doc.first_publish_year ? String(doc.first_publish_year) : '',
        source: 'Open Library',
      };
    });
  } catch (err) {
    if (err.name === 'AbortError') throw err;
    return [];
  }
}

// 5. Fetch from Internet Archive Texts API with subject genre
async function fetchInternetArchive(query, filterBy, signal) {
  try {
    let qString = `(${query}) AND mediatype:(texts)`;
    if (filterBy === 'title') qString = `title:(${query}) AND mediatype:(texts)`;
    else if (filterBy === 'author') qString = `creator:(${query}) AND mediatype:(texts)`;
    else if (filterBy === 'subject') qString = `subject:(${query}) AND mediatype:(texts)`;

    const endpoint = `https://archive.org/advancedsearch.php?q=${encodeURIComponent(
      qString
    )}&fl[]=identifier,title,creator,year,subject&rows=8&output=json`;

    const res = await fetch(endpoint, { signal });
    if (!res.ok) return [];

    const data = await res.json();
    const docs = data.response?.docs || [];
    if (docs.length === 0) return [];

    return docs.map((doc) => {
      const titleStr = Array.isArray(doc.title)
        ? doc.title.join(' ')
        : String(doc.title || 'Untitled Document');
      const authorStr = Array.isArray(doc.creator)
        ? doc.creator.join(', ')
        : String(doc.creator || 'Internet Archive Contributor');

      const genre = cleanGenre(doc.subject, 'Historical Literature');

      return {
        id: `ia-${doc.identifier}`,
        title: titleStr,
        author: authorStr,
        genre: genre,
        category: genre,
        total_pages: 200,
        thumbnail_url: `https://archive.org/services/img/${doc.identifier}`,
        description: 'Digitized historical edition archived by the Internet Archive.',
        publishedDate: doc.year ? String(doc.year) : '',
        source: 'Internet Archive',
      };
    });
  } catch (err) {
    if (err.name === 'AbortError') throw err;
    return [];
  }
}

/**
 * Master Federated Search Algorithm across multiple providers with filtering and sorting
 */
export async function searchBooksAlgorithm(
  query,
  filterBy = 'all',
  sortBy = 'relevance',
  provider = 'all',
  signal
) {
  const trimmed = query.trim();

  // 1. If empty, return curated recommendations instantly
  if (!trimmed) {
    const rawCurated = CURATED_SUGGESTIONS.slice(0, 6);
    const sorted = applySortToResults(rawCurated, sortBy);
    return {
      results: sorted,
      source: 'Curated Recommendations',
      isCurated: true,
    };
  }

  // 2. Check LRU In-Memory Cache (0ms response)
  const cacheKey = `${provider}::${filterBy}::${sortBy}::${trimmed.toLowerCase()}`;
  if (SEARCH_CACHE.has(cacheKey)) {
    return SEARCH_CACHE.get(cacheKey);
  }

  let finalResults = [];
  let sourceLabel = 'All Sources';

  // 3. Provider Routing
  if (provider === 'curated') {
    finalResults = getLocalCuratedSuggestions(trimmed, filterBy);
    sourceLabel = 'Curated Vault';
  } else if (provider === 'openlibrary') {
    finalResults = await fetchOpenLibrary(trimmed, filterBy, signal);
    sourceLabel = 'Open Library';
  } else if (provider === 'gutenberg') {
    finalResults = await fetchGutendex(trimmed, filterBy, signal);
    sourceLabel = 'Project Gutenberg';
  } else if (provider === 'archive') {
    finalResults = await fetchInternetArchive(trimmed, filterBy, signal);
    sourceLabel = 'Internet Archive';
  } else if (provider === 'googlebooks') {
    const gb = await fetchGoogleBooks(trimmed, filterBy, signal);
    finalResults = gb || (await fetchOpenLibrary(trimmed, filterBy, signal));
    sourceLabel = gb ? 'Google Books' : 'Open Library (Fallback)';
  } else {
    // 'all': Federated Multi-Source Search in Parallel
    sourceLabel = 'Federated Multi-Source';

    const [olPromise, gdPromise, iaPromise, gbPromise] = await Promise.allSettled([
      fetchOpenLibrary(trimmed, filterBy, signal),
      fetchGutendex(trimmed, filterBy, signal),
      fetchInternetArchive(trimmed, filterBy, signal),
      !isGoogleBooksThrottled ? fetchGoogleBooks(trimmed, filterBy, signal) : Promise.resolve([]),
    ]);

    const olResults = olPromise.status === 'fulfilled' ? olPromise.value || [] : [];
    const gdResults = gdPromise.status === 'fulfilled' ? gdPromise.value || [] : [];
    const iaResults = iaPromise.status === 'fulfilled' ? iaPromise.value || [] : [];
    const gbResults = gbPromise.status === 'fulfilled' ? gbPromise.value || [] : [];
    const localMatches = getLocalCuratedSuggestions(trimmed, filterBy);

    // Merge in interleaved order for rich source variety
    const combined = [];
    const maxLen = Math.max(olResults.length, gdResults.length, gbResults.length, iaResults.length, localMatches.length);

    for (let i = 0; i < maxLen; i++) {
      if (olResults[i]) combined.push(olResults[i]);
      if (gdResults[i]) combined.push(gdResults[i]);
      if (gbResults[i]) combined.push(gbResults[i]);
      if (iaResults[i]) combined.push(iaResults[i]);
      if (localMatches[i]) combined.push(localMatches[i]);
    }

    // Deduplicate by normalized title & author
    const seen = new Set();
    const deduplicated = [];

    for (const item of combined) {
      const key = normalize(item.title) + '::' + normalize(item.author);
      if (!seen.has(key)) {
        seen.add(key);
        deduplicated.push(item);
      }
      if (deduplicated.length >= 12) break;
    }

    finalResults = deduplicated.length > 0 ? deduplicated : localMatches;
  }

  // 4. Apply sort
  const sortedResults = applySortToResults(finalResults, sortBy);

  const responsePayload = {
    results: sortedResults,
    source: sourceLabel,
    isCurated: provider === 'curated' || (sortedResults.length === 0 && trimmed === ''),
  };

  // Cache response
  if (SEARCH_CACHE.size >= MAX_CACHE_ENTRIES) {
    const firstKey = SEARCH_CACHE.keys().next().value;
    SEARCH_CACHE.delete(firstKey);
  }
  SEARCH_CACHE.set(cacheKey, responsePayload);

  return responsePayload;
}
